# EXERCISE 3 - Domain mixture weighting
# ======================================================================

@dataclass
class Exercise3Solution:
    """
    Assign random domain labels to high-quality docs, then compute the
    weighted mean quality score under two weight vectors:

        uniform    = (web=1, code=1, paper=1, book=1)
        code_heavy = (web=1, code=3, paper=1, book=1)

    The output shows how mixture weights amplify the mean quality of
    the surviving corpus - the mechanism behind domain re-weighting in
    code-heavy LLM pretraining.
    """
    seed: int = SEED
    domains: Tuple[str, ...] = ("web", "code", "paper", "book")
    weight_vectors: Tuple[Tuple[str, Dict[str, float]], ...] = (
        ("uniform",    {"web": 1.0, "code": 1.0, "paper": 1.0, "book": 1.0}),
        ("code_heavy", {"web": 1.0, "code": 3.0, "paper": 1.0, "book": 1.0}),
    )

    def run(self) -> pd.DataFrame:
        rng = np.random.default_rng(self.seed)
        corpus = _labelled_corpus(self.seed)

        # Only high-quality and near-dup documents carry "knowledge";
        # give each a random domain label (in production this comes
        # from URL/whitelists or a domain classifier).
        knowledge_docs = [d for d in corpus
                          if d.metadata["label"] in {"high", "near_dup"}]
        for d in knowledge_docs:
            d.source = self.domains[int(rng.integers(len(self.domains)))]

        # Train classifier on held-out seeds
        hq = [d.text for d in corpus if d.metadata["label"] == "high"][:50]
        lq = [d.text for d in corpus if d.metadata["label"] == "low"][:25]
        classifier = QualityClassifier(seed=self.seed).fit(hq, lq)

        # Score every knowledge doc once
        scores = {d.doc_id: classifier.score(d.text) for d in knowledge_docs}
        domains_of = {d.doc_id: d.source for d in knowledge_docs}

        rows = []
        for name, weights in self.weight_vectors:
            num = sum(weights[domains_of[i]] * s for i, s in scores.items())
            den = sum(weights[domains_of[i]] for i in scores)
            rows.append(dict(
                mixture=name,
                weighted_mean_score=num / den if den else 0.0,
                unweighted_mean_score=float(np.mean(list(scores.values()))),
            ))
        return pd.DataFrame(rows)

    def plot(self, df: pd.DataFrame, save_to: str = "fig_ex3.png") -> None:
        fig, ax = plt.subplots(figsize=(7, 4.5))
        x = np.arange(len(df))
        w = 0.35
        ax.bar(x - w / 2, df["unweighted_mean_score"], w,
               label="unweighted", color="steelblue")
        ax.bar(x + w / 2, df["weighted_mean_score"], w,
               label="weighted", color="seagreen")
        ax.set_xticks(x)
        ax.set_xticklabels(df["mixture"])
        ax.set_ylabel("Mean quality score")
        ax.set_title("Exercise 3 - Domain mixture weights change effective quality")
        ax.legend()
        ax.grid(True, axis="y", alpha=0.3)
        fig.tight_layout()
        fig.savefig(save_to, dpi=150)
        plt.show()
        print(f"[Ex3] saved {Path(save_to).resolve()}")


