# EXERCISE 2 - Heuristic vs classifier precision / recall
# ======================================================================

@dataclass
class Exercise2Solution:
    """
    Compute precision and recall of "low-quality removal" for the
    heuristic filter and for the trained quality classifier on the same
    labelled corpus. The classifier is trained on a held-out split so
    metrics are not trivially 1.0.
    """
    seed: int = SEED
    quality_threshold: float = 0.5

    def run(self) -> pd.DataFrame:
        corpus = _labelled_corpus(self.seed)

        # --- Held-out split for classifier training -------------------
        high_seeds = [d.text for d in corpus
                      if d.metadata["label"] == "high"][:50]
        low_seeds = [d.text for d in corpus
                     if d.metadata["label"] == "low"][:25]
        classifier = QualityClassifier(seed=self.seed).fit(high_seeds, low_seeds)

        # --- Apply both filters to the whole corpus ------------------
        _, h_stats = HeuristicFilter(PipelineConfig()).apply(corpus)
        _, q_stats = classifier.apply(corpus, threshold=self.quality_threshold)

        def _metrics(removed_ids: List[str], corpus: List[Document]) -> Dict[str, float]:
            truth = {d.doc_id: (d.metadata.get("label") == "low") for d in corpus}
            tp = sum(1 for i in removed_ids if truth.get(i, False))
            fp = sum(1 for i in removed_ids if not truth.get(i, False))
            fn = sum(1 for i, is_low in truth.items()
                     if is_low and i not in set(removed_ids))
            precision = tp / (tp + fp) if (tp + fp) else 0.0
            recall = tp / (tp + fn) if (tp + fn) else 0.0
            return dict(precision=precision, recall=recall, tp=tp, fp=fp, fn=fn)

        h = _metrics(h_stats["removed_ids"], corpus)
        q = _metrics(q_stats["removed_ids"], corpus)
        return pd.DataFrame([
            dict(method="heuristic", **h),
            dict(method="classifier", **q),
        ])

    def plot(self, df: pd.DataFrame, save_to: str = "fig_ex2.png") -> None:
        fig, ax = plt.subplots(figsize=(8, 4.5))
        x = np.arange(len(df))
        w = 0.35
        ax.bar(x - w / 2, df["precision"], w, label="precision", color="steelblue")
        ax.bar(x + w / 2, df["recall"], w, label="recall", color="darkorange")
        ax.set_xticks(x)
        ax.set_xticklabels(df["method"])
        ax.set_ylim(0, 1.05)
        ax.set_ylabel("Score")
        ax.set_title("Exercise 2 - Low-quality removal: precision & recall")
        ax.legend()
        ax.grid(True, axis="y", alpha=0.3)
        fig.tight_layout()
        fig.savefig(save_to, dpi=150)
        plt.show()
        print(f"[Ex2] saved {Path(save_to).resolve()}")


