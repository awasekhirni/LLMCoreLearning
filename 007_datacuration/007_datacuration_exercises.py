# ======================================================================
# EXERCISE 1 - Jaccard threshold sweep
# ======================================================================

@dataclass
class Exercise1Solution:
    """
    Sweep Jaccard threshold over a fixed grid and, for each value,
    compute (a) the number of docs removed by near-dedup, and (b) the
    mean cluster size (as a proxy for how aggressive dedup is).

    Teaching point: low thresholds over-dedup (merging distinct docs);
    high thresholds under-dedup (leaving near-duplicates in).
    """
    thresholds: Tuple[float, ...] = (0.5, 0.6, 0.7, 0.8, 0.9, 0.95)
    seed: int = SEED

    def run(self) -> pd.DataFrame:
        corpus = _labelled_corpus(self.seed)
        # Run exact dedup first so near-dedup operates on unique docs only.
        after_exact, _ = ExactDeduplicator().apply(corpus)
        rows = []
        for th in self.thresholds:
            stage = NearDuplicateDeduplicator(threshold=th)
            kept, stats = stage.apply(after_exact)
            # Ground truth: how many labelled near-duplicates remain?
            remaining_near_dups = sum(
                1 for d in kept if d.metadata.get("label") == "near_dup"
            )
            rows.append(dict(
                threshold=th,
                n_removed=stats["n_removed"],
                n_kept=stats["n_out"],
                mean_cluster_size=stats["mean_cluster_size"],
                remaining_near_dups=remaining_near_dups,
            ))
        return pd.DataFrame(rows)

    def plot(self, df: pd.DataFrame, save_to: str = "fig_ex1.png") -> None:
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(13, 4.5))
        ax1.plot(df["threshold"], df["n_removed"], marker="o", color="steelblue")
        ax1.set_title("Exercise 1 - Docs removed vs Jaccard threshold")
        ax1.set_xlabel("MinHash Jaccard threshold")
        ax1.set_ylabel("Documents removed")
        ax1.grid(True, alpha=0.3)

        ax2.plot(df["threshold"], df["remaining_near_dups"],
                 marker="s", color="darkorange")
        ax2.set_title("Exercise 1 - Remaining near-dups vs threshold")
        ax2.set_xlabel("MinHash Jaccard threshold")
        ax2.set_ylabel("Labelled near-dups still in the corpus")
        ax2.grid(True, alpha=0.3)
        fig.tight_layout()
        fig.savefig(save_to, dpi=150)
        plt.show()
        print(f"[Ex1] saved {Path(save_to).resolve()}")


